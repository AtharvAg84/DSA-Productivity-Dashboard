import openpyxl, re, json, datetime as dt, collections
U='/mnt/user-data/uploads/'
MON={m:i+1 for i,m in enumerate('jan feb mar apr may jun jul aug sep oct nov dec'.split())}
rep=collections.Counter(); notes=[]
def clean(s):
    if s is None: return ''
    s=re.sub(r'\s+',' ',str(s).replace('\n',' ')).strip()
    return '' if s in ('-','--') else s
def lst(s):
    out=[]
    for p in re.split(r'[,\n&/]+',str(s or '')):
        p=re.sub(r'\s+',' ',p).strip()
        if p and p!='-' and p.lower() not in [o.lower() for o in out]: out.append(p)
    return ', '.join(out)
def mins(v):
    if isinstance(v,dt.time): return v.hour*60+v.minute
    if isinstance(v,str):
        m=re.fullmatch(r'\s*(\d+):(\d+)\s*',v)
        if m: rep['time text parsed (e.g. 0:5)']+=1; return int(m[1])*60+int(m[2])
    return None
def diff(s):
    f=re.findall(r'easy|med\w*|hard',str(s or ''),re.I); o=[]
    for x in f:
        x='Medium' if x.lower().startswith('med') else x.title()
        if x not in o:o.append(x)
    return ', '.join(o)
def tc(s):
    f=re.findall(r'PASS|FAIL',str(s or '').upper()); return '/'.join(dict.fromkeys(f))
def ok(s):
    s=str(s or '').strip().upper(); return 'Yes' if s=='YES' else 'No' if s=='NO' else ''
def mk(year,mon,day):
    m=MON.get(str(mon).strip().lower()[:3])
    if not m or not isinstance(day,int): return None
    try: return dt.date(year,m,day).isoformat()
    except ValueError: rep['invalid date skipped']+=1; return None

PL={'leetcode':'LeetCode','leetcode contest':'LeetCode','live contest leet':'LeetCode','gfg':'GeeksforGeeks','geeksforgeeks':'GeeksforGeeks','codeforces':'Codeforces','cf':'Codeforces','hackerrank':'HackerRank','coding ninja':'Coding Ninjas','coding ninjas':'Coding Ninjas','codingninja':'Coding Ninjas','codeninja':'Coding Ninjas','codechef':'CodeChef'}
TP={'array':'Arrays','sort':'Sorting','dp':'Dynamic Programming','dynamic prog':'Dynamic Programming','math':'Math','maths':'Math','string':'Strings','linkedlist':'Linked List','graph':'Graphs','binarysearch':'Binary Search','bs':'Binary Search','tree':'Trees','stack':'Stacks','2 pointers':'Two Pointers','2 pointer':'Two Pointers','two pointer':'Two Pointers','bit':'Bit Manipulation','bit mani':'Bit Manipulation','manipulation':'Bit Manipulation','sorting':'Sorting','kadane algorithm':'Kadane'}
CO={'couchbase':'Couchbase','ringcentral prep':'RingCentral','ringcentral':'RingCentral','meesho':'Meesho','flipkart':'Flipkart'}
def _parts(s): return [re.sub(r'\s+',' ',p).strip() for p in re.split(r'[,\n&/+.]+',str(s or '')) if p.strip() not in ('','-')]
def _uniq(l):
    o=[]
    for x in l:
        if x not in o:o.append(x)
    return o
def plats(s):
    raw=str(s or '').lower(); l=_uniq([PL.get(p.lower(),p) for p in _parts(s)])
    return ', '.join(l), ('contest' in raw)
def tops(s,contest=False):
    l=[TP.get(p.lower(),p) for p in _parts(s) if p.lower() not in CO]
    if contest: l.append('Contest')
    return ', '.join(_uniq(l))
def cos(s): return ', '.join(_uniq([CO[p.lower()] for p in _parts(s) if p.lower() in CO]))
out=[]
# Desktop (2025, learning phase)
ws=openpyxl.load_workbook(U+'Desktop.xlsx',data_only=True).active
for r in ws.iter_rows(min_row=2,max_col=11,values_only=True):
    d=mk(2025,r[0],r[1])
    if not d: rep['Desktop: separator/banner rows skipped']+=1; continue
    sub=r[4]; n=sub if isinstance(sub,int) else sum(map(int,re.findall(r'\d+',sub))) if isinstance(sub,str) else 0
    if isinstance(sub,str) and '\n' in sub: rep['Desktop: multi-platform submissions summed']+=1
    t=mins(r[2]); v=clean(r[3])
    if n==0 and t is None and not v: rep['Desktop: dated rows with nothing logged skipped']+=1; continue
    out.append(dict(d=d,ph='L',n=n,r=0,t=t,v=v,w=plats(r[5])[0],tp=tops(r[6],plats(r[5])[1]),rv='',co='',ty=diff(r[7]),ok=ok(r[8]),tc=tc(r[9]),nt=clean(r[10])))
# Challenge (Dec 2025 -> 2026, execution phase)
ws=openpyxl.load_workbook(U+'Challenge_Yourself.xlsx',data_only=True).active
for r in ws.iter_rows(min_row=2,max_col=12,values_only=True):
    mo=str(r[0] or '').strip().lower()[:3]
    d=mk(2025 if mo=='dec' else 2026,r[0],r[1])
    if not d: rep['Challenge: empty/undated rows skipped']+=1; continue
    n=r[9] if isinstance(r[9],int) else 0; rv=r[7] if isinstance(r[7],int) else 0
    if r[10] not in (None,n+rv): rep['Challenge: Total mismatch vs Completed+Rev']+=1; notes.append((d,r[10],n+rv))
    t=mins(r[2]); v=clean(r[3])
    if n+rv==0 and t is None and not v: rep['Challenge: dated rows with nothing logged skipped']+=1; continue
    out.append(dict(d=d,ph='C',n=n,r=rv,t=t,v=v,w=plats(r[4])[0],tp=tops(r[5],plats(r[4])[1]),rv=tops(r[6]),co=cos(r[6]),ty=diff(r[8]),ok='',tc='',nt=clean(r[11])))
out.sort(key=lambda e:(e['d'],e['ph']))
dups=[d for d,c in collections.Counter(e['d'] for e in out).items() if c>1]
open('/mnt/user-data/outputs/dsa-tracker/data/data.js','w').write('/* Generated by build_data.py from Desktop.xlsx + Challenge_Yourself.xlsx */\nwindow.DSA_DATA='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
act=lambda e:e['n']+e['r']>0 or e['t'] or e['v']
print('records',len(out),'| learning',sum(e['ph']=='L' for e in out),'| challenge',sum(e['ph']=='C' for e in out))
print('range',out[0]['d'],'->',out[-1]['d'],'| total problems',sum(e['n']+e['r'] for e in out),'| revised',sum(e['r'] for e in out),'| minutes',sum(e['t'] or 0 for e in out),'| days w/ time',sum(e['t'] is not None for e in out))
print('duplicate dates',dups,'| mismatches',notes[:5]); print(dict(rep))
